/**
 * أدوات النص: التهريب، وتطبيع العربية، والبحث الذكي.
 */
AIMED.نص = {
  /** كل قيمة تدخل HTML تمرّ من هنا. */
  هرّب(س) {
    return String(س == null ? '' : س)
      .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;').replace(/'/g, '&#39;');
  },

  /**
   * تطبيع عربي: أ/إ/آ ← ا · ة ← ه · ى ← ي · حذف التشكيل والتطويل.
   * كي لا يكون «الرئة» و«الرءة» شيئين مختلفين في البحث.
   */
  طبّععربي(س) {
    return String(س || '')
      .replace(/[ً-ْٰـ]/g, '')
      .replace(/[أإآٱ]/g, 'ا')
      .replace(/ة/g, 'ه')
      .replace(/ى/g, 'ي')
      .replace(/ؤ/g, 'و')
      .replace(/ئ/g, 'ي')
      .toLowerCase().trim();
  },

  /** الأرقام العربية-الهندية ← لاتينية، كي يجد من كتب ٥ الرقم 5. */
  طبّعالأرقام(س) {
    return String(س || '').replace(/[٠-٩]/g, (d) => String(d.charCodeAt(0) - 0x0660));
  },

  /** مفتاح المقارنة الموحّد لكل بحث في الموقع. */
  مفتاح(س) { return this.طبّععربي(this.طبّعالأرقام(س)); },

  /**
   * صيغة العدد العربية الصحيحة.
   * صيغ = [مفرد, مثنى, جمع قلة (3-10), تمييز مفرد منصوب (11+)]
   * مثال: عدّ(5, ['جواب','جوابان','أجوبة','جوابًا']) ← «5 أجوبة»
   */
  عدّ(ع, صيغ) {
    if (ع === 0) return 'لا ' + صيغ[2];
    if (ع === 1) return صيغ[0];
    if (ع === 2) return صيغ[1];
    if (ع <= 10) return ع + ' ' + صيغ[2];
    return ع + ' ' + صيغ[3];
  },

  أجوبة(ع) { return this.عدّ(ع, ['جواب واحد', 'جوابان', 'أجوبة', 'جوابًا']); },
  أجهزة(ع) { return this.عدّ(ع, ['جهاز واحد', 'جهازان', 'أجهزة', 'جهازًا']); },
  مصادر(ع) { return this.عدّ(ع, ['مصدر واحد', 'مصدران', 'مصادر', 'مصدرًا']); },

  /** يغلّف الأرقام في نصٍّ مهرَّب بوسم يعطيها وزن 200 — الرقم يُقرأ لا يصرخ. */
  بأرقام(نص) { return String(نص).replace(/(\d+)/g, '<span class="رقم">$1</span>'); },

  /** يبرز مواضع الاستعلام داخل نصّ آمن للعرض. */
  أبرز(نص, استعلام) {
    const آمن = this.هرّب(نص);
    if (!استعلام) return آمن;
    const ك = this.مفتاح(استعلام).split(/\s+/).filter((w) => w.length > 1);
    if (!ك.length) return آمن;
    const نمط = new RegExp('(' + ك.map((w) => w.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|') + ')', 'gi');
    return آمن.replace(نمط, '<mark>$1</mark>');
  },
};
