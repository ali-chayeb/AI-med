/**
 * قطع عرض مشتركة بين أكثر من واجهة.
 */
AIMED.عرض = AIMED.عرض || {};

/**
 * ختم الحداثة: اسم الدليل وسنته، ولون كهرماني إن تجاوز المهلة.
 * هذا تجسيد للقاعدة 8a — الموقع هو الذي يتذكّر، لا أنت.
 */
AIMED.عرض.ختم = function (بطاقة) {
  if (!بطاقة.دليل && !بطاقة.سنةالدليل) return '';
  const هـ = AIMED.نص.هرّب;
  const السنة = new Date().getFullYear();
  const عمر = بطاقة.سنةالدليل ? السنة - بطاقة.سنةالدليل : null;
  const قديم = عمر !== null && عمر > AIMED.إعداد.عمرالدليل;
  const وصف = قديم ? `مضى على هذا الدليل ${عمر} سنوات — يحتاج مراجعة` : 'الدليل المعتمد في هذا الجواب';
  return `<span class="ختم" data-دليل${قديم ? ' data-حالة="قديم"' : ''} title="${هـ(وصف)}">`
    + `${هـ(بطاقة.دليل || '—')}${بطاقة.سنةالدليل ? ' · ' + بطاقة.سنةالدليل : ''}`
    + `</span>`;
};

/** سطر جواب في القوائم الطويلة (البيت، نتائج الجهاز). */
AIMED.عرض.سطرجواب = function (ج, معالجهاز) {
  const هـ = AIMED.نص.هرّب;
  return `<a class="سطر-جواب" href="#/جواب/${encodeURIComponent(ج.slug)}">`
    + `<span class="رمز" title="${هـ(AIMED.إعداد.الأنواع[ج.نوع]?.اسم || ج.نوع)}">${هـ(AIMED.رمزنوع(ج.نوع))}</span>`
    + `<span class="عنوان">${هـ(ج.عنوان)}${ج.اختصار ? ` <span class="فرع">${هـ(ج.اختصار)}</span>` : ''}</span>`
    + `<span class="فرع">${معالجهاز ? هـ(ج.جهاز) : AIMED.عرض.ختم(ج)}</span>`
    + `</a>`;
};
