/**
 * البيت: الأجهزة كشبكة، ثم آخر ما أُضيف، ثم ما يحتاج مراجعة.
 * لا واجهة ترحيبية ولا رسوم — الصفحة الأولى هي الفهرس نفسه.
 */
AIMED.عرض = AIMED.عرض || {};

AIMED.عرض.البيت = {
  ارسم(عنصر) {
    const هـ = AIMED.نص.هرّب;
    const أجهزة = AIMED.مخزن.الأجهزة();
    const الكل = AIMED.مخزن.الكل();

    if (!الكل.length) {
      عنصر.innerHTML = `
        <div class="بيت-رأس">
          <h1 class="بيت-عنوان">لا أجوبة بعد</h1>
          <p class="بيت-وصف">ضع ملفات الأجوبة في <code>2-الأجوبة/</code> ثم شغّل
             <code>node 5-أدوات/بناء.mjs</code>، وستظهر هنا مرتّبة حسب الجهاز.</p>
        </div>`;
      return;
    }

    const صفوفالأجهزة = أجهزة.map((د) => {
      const أنواع = Object.entries(د.أنواع)
        .sort((a, b) => b[1] - a[1])
        .map(([ن, ع]) => `<span title="${هـ(AIMED.إعداد.الأنواع[ن]?.اسم || ن)}">${هـ(AIMED.رمزنوع(ن))}&nbsp;${ع}</span>`)
        .join('');
      return `<a class="صف-رف" href="#/جهاز/${encodeURIComponent(د.اسم)}">`
        + `<span class="صف-رف-اسم">${هـ(د.اسم)}</span>`
        + `<span class="صف-رف-أنواع">${أنواع}</span>`
        + `<span class="صف-رف-عدد">${د.أجوبة.length}</span>`
        + `</a>`;
    }).join('');

    const أحدث = AIMED.مخزن.الأحدث(8).map((ج) => AIMED.عرض.سطرجواب(ج, true)).join('');
    const قديم = AIMED.مخزن.تحتاجمراجعة();

    عنصر.innerHTML = `
      <div class="بيت-رأس">
        <h1 class="بيت-عنوان">${AIMED.نص.بأرقام(AIMED.نص.أجوبة(الكل.length))} في ${AIMED.نص.بأرقام(AIMED.نص.أجهزة(أجهزة.length))}</h1>
        <p class="بيت-وصف">اختر جهازًا، أو ابحث بالاسم أو المصطلح. متن الأجوبة بالإنجليزية،
           وكل معلومة فيها مرقّمة إلى مصدرها.</p>
      </div>

      <div class="لوح-أجهزة">${صفوفالأجهزة}</div>

      <section class="قسم-بيت">
        <h2 class="قسم-بيت-عنوان"><span>آخر ما أُضيف</span></h2>
        ${أحدث}
      </section>

      ${قديم.length ? `
      <section class="قسم-بيت قسم-بيت--معلَّم">
        <h2 class="قسم-بيت-عنوان">
          <span>يحتاج مراجعة — مضى على دليله أكثر من سنتين</span>
          <span class="فرع">${قديم.length}</span>
        </h2>
        ${قديم.map((ج) => AIMED.عرض.سطرجواب(ج, true)).join('')}
      </section>` : ''}
    `;
  },

  /** صفحة جهاز واحد: كل أجوبته مصنّفة حسب النوع. */
  ارسمجهازًا(عنصر, اسم) {
    const هـ = AIMED.نص.هرّب;
    const د = AIMED.مخزن.الأجهزة().find((x) => x.اسم === اسم);

    if (!د) {
      عنصر.innerHTML = `<div class="بيت-رأس"><h1 class="بيت-عنوان">لا جهاز باسم «${هـ(اسم)}»</h1>
        <p class="بيت-وصف"><a href="#/">عُد إلى الفهرس</a></p></div>`;
      return;
    }

    const حسبالنوع = {};
    for (const ج of د.أجوبة) (حسبالنوع[ج.نوع] = حسبالنوع[ج.نوع] || []).push(ج);

    const أقسام = Object.keys(AIMED.إعداد.الأنواع)
      .filter((ن) => حسبالنوع[ن])
      .map((ن) => `
        <section class="قسم-بيت">
          <h2 class="قسم-بيت-عنوان">
            <span>${هـ(AIMED.رمزنوع(ن))}&nbsp;&nbsp;${هـ(AIMED.إعداد.الأنواع[ن].اسم)}</span>
            <span class="فرع">${حسبالنوع[ن].length}</span>
          </h2>
          ${حسبالنوع[ن].map((ج) => AIMED.عرض.سطرجواب(ج, false)).join('')}
        </section>`).join('');

    عنصر.innerHTML = `
      <div class="بيت-رأس">
        <p class="جواب-مسار"><a href="#/">الفهرس</a><span>/</span><span>${هـ(د.اسم)}</span></p>
        <h1 class="بيت-عنوان">${هـ(د.اسم)}</h1>
        <p class="بيت-وصف">${AIMED.نص.أجوبة(د.أجوبة.length)}.</p>
      </div>
      ${أقسام}`;
  },
};
