/**
 * صفحة الجواب.
 * المتن يصل من أداة البناء كـ HTML جاهز — لا تحويل Markdown في المتصفح.
 */
AIMED.عرض = AIMED.عرض || {};

AIMED.عرض.الجواب = {
  ارسم(عنصر, بطاقة, جواب) {
    const هـ = AIMED.نص.هرّب;

    const شارات = [
      `<span class="ختم" title="نوع السؤال">${هـ(AIMED.رمزنوع(بطاقة.نوع))} ${هـ(AIMED.إعداد.الأنواع[بطاقة.نوع]?.اسم || بطاقة.نوع)}</span>`,
      AIMED.عرض.ختم(بطاقة),
      بطاقة.مصادر ? `<span class="ختم" title="عدد المصادر">${AIMED.نص.مصادر(بطاقة.مصادر)}</span>` : '',
    ].filter(Boolean).join('');

    const أقسام = جواب.أقسام.map((ق, i) => {
      const إنذار = /red\s*flags?|علامات\s*الإنذار/i.test(ق.عنوان);
      return `<section class="قسم" id="${هـ(ق.معرّف)}"${إنذار ? ' data-إنذار' : ''}>`
        + `<h2 class="قسم-عنوان"><span class="قسم-رقم">${String(i + 1).padStart(2, '0')}</span>`
        + `<span>${هـ(ق.عنوان)}</span></h2>`
        + `<div class="متن">${ق.html}</div>`
        + `</section>`;
    }).join('');

    const مصادرللطباعة = جواب.مصادر.length
      ? `<div class="مصادر-للطباعة"><h2 class="قسم-عنوان"><span>Sources</span></h2>`
        + `<div class="متن"><ol>${جواب.مصادر.map((م) => `<li>${م.نص}</li>`).join('')}</ol></div></div>`
      : '';

    عنصر.innerHTML = `
      <header class="جواب-رأس">
        <p class="جواب-مسار">
          <a href="#/">الفهرس</a><span>/</span>
          <a href="#/جهاز/${encodeURIComponent(بطاقة.جهاز)}">${هـ(بطاقة.جهاز)}</a>
        </p>
        <h1 class="جواب-عنوان">${هـ(جواب.عنوان)}${بطاقة.اختصار ? ` <span class="خفيف">${هـ(بطاقة.اختصار)}</span>` : ''}</h1>
        ${بطاقة.عربي ? `<p class="جواب-عربي">${هـ(بطاقة.عربي)}</p>` : ''}
        ${بطاقة.ملخص ? `<p class="جواب-ملخص">${هـ(بطاقة.ملخص)}</p>` : ''}
        <div class="جواب-شارات">${شارات}</div>
      </header>
      ${جواب.تمهيد ? `<div class="متن">${جواب.تمهيد}</div>` : ''}
      ${أقسام}
      ${مصادرللطباعة}`;

    this.اربطالاستشهادات(عنصر);
  },

  /** النقر على [1] يبرز المصدر في الهامش بدل القفز إلى أسفل الصفحة. */
  اربطالاستشهادات(عنصر) {
    عنصر.addEventListener('click', (ح) => {
      const س = ح.target.closest('.استشهاد');
      if (!س) return;
      ح.preventDefault();
      const رقم = (س.dataset['مصادر'] || '').split(/[,،-]/)[0].trim();
      AIMED.عرض.الهامش.أبرزمصدرًا(رقم);
    });
  },

  تعذّر(عنصر, slug) {
    const هـ = AIMED.نص.هرّب;
    عنصر.innerHTML = `
      <div class="بيت-رأس">
        <h1 class="بيت-عنوان">تعذّر تحميل هذا الجواب</h1>
        <p class="بيت-وصف">الملف <code>بيانات/أجوبة/${هـ(slug)}.js</code> غير موجود.
           شغّل <code>node 5-أدوات/بناء.mjs</code> ثم أعد التحميل.</p>
        <p class="بيت-وصف"><a href="#/">عُد إلى الفهرس</a></p>
      </div>`;
  },
};
