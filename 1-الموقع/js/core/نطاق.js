/**
 * النطاق العام والإعدادات الثابتة.
 * كل شيء تحت AIMED — لا متغيّرات عامة أخرى عدا AIMED نفسه.
 */
window.AIMED = window.AIMED || {};

AIMED.إعداد = {
  // أنواع الأسئلة — البادئة هي نفسها المستعملة في «قواعد المحادثة».
  الأنواع: {
    مرض:     { رمز: '#', اسم: 'مرض' },
    عرض:     { رمز: '=', اسم: 'عرض أو علامة' },
    جهاز:    { رمز: '!', اسم: 'جهاز' },
    استقصاء: { رمز: '?', اسم: 'استقصاء' },
    فحص:     { رمز: '%', اسم: 'فحص سريري' },
    دواء:    { رمز: '^', اسم: 'دواء' },
    مختصر:   { رمز: '$', اسم: 'جواب مختصر' },
    مصطلح:   { رمز: '@', اسم: 'مصطلح' },
  },

  // ترتيب ثابت للأجهزة في الرفّ. أي جهاز غير مذكور يأتي بعدها أبجديًا.
  ترتيبالأجهزة: [
    'قلبية', 'تنفسية', 'هضمية', 'كلوية', 'عصبية', 'غدد',
    'دموية', 'رثوية', 'إنتانية', 'جلدية', 'إسعاف', 'عامة',
  ],

  // القاعدة 8a: دليل أقدم من هذا العدد من السنين يُوسم «يحتاج مراجعة».
  عمرالدليل: 2,
};

/** رمز النوع، أو علامة استفهام إن كان النوع مجهولًا. */
AIMED.رمزنوع = (نوع) => (AIMED.إعداد.الأنواع[نوع] || { رمز: '·' }).رمز;

/** ترتيب جهاز في الرفّ. */
AIMED.ترتيبجهاز = (جهاز) => {
  const i = AIMED.إعداد.ترتيبالأجهزة.indexOf(جهاز);
  return i < 0 ? 900 : i;
};
